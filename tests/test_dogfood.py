"""Dogfood results on two public pydantic-evals examples (SPEC.md §11 M5, docs/dogfood.md).

The reports in tests/fixtures/dogfood/ are generated by scripts/make_dogfood_reports.py.
These tests pin every finding docs/dogfood.md describes, so the write-up cannot drift
from what eval-preflight actually reports.
"""

from pathlib import Path

import pytest

from eval_preflight import CheckResult, Finding, check, load
from eval_preflight.cli import main

DOGFOOD = Path(__file__).parent / "fixtures" / "dogfood"

FRIENDLY_JUDGE = (
    "LLMJudge('Ensure the explanation or error_message fields are truly appropriate for"
    " user display, in a second-person or friendly style.')"
)
MAY_JUDGE = (
    "LLMJudge('We want to interpret conflicting references by default to the more recent"
    " timeframe; confirm the explanation addresses ignoring early May.')"
)
AGENT_CALLED_TOOL = "AgentCalledTool(agent_name='time_range_agent', tool_name='get_current_time')"
ERROR_CASES = ["Impossible range", "No mention", "Confusing relative references"]


def run(name: str) -> CheckResult:
    loaded = load(DOGFOOD / f"{name}.json")
    assert loaded.source == "pydantic-evals"
    return check(loaded)


def estimator(result: CheckResult, key: str, value: str) -> Finding:
    (finding,) = [
        f for f in result.by_check("aggregation-consistency") if f.details.get(key) == value
    ]
    return finding


def severities(findings: list[Finding]) -> dict[str, str]:
    return {f.details["evaluator_id"]: f.severity for f in findings}


def test_title_case_example_is_a_clean_pass() -> None:
    result = run("title_case")

    assert result.verdict == "PASS"
    assert {f.severity for f in result.findings} == {"PASS"}
    # Integrity is not correctness: has_capitals fails on 2 of 8 cases and the run still
    # passes, because every number is complete and attributed to the right evaluator.
    has_capitals = estimator(
        result, "evaluator_id", "Contains(evaluation_name='has_capitals', value='H')[has_capitals]"
    )
    assert has_capitals.details["pooled"] == 0.75


def test_time_range_case_level_judge_takes_the_dataset_judges_name() -> None:
    by_kind = {
        (f.details["kind"], f.details.get("display_name") or f.details.get("evaluator_id")): f
        for f in run("time_range").by_check("name-collision")
    }

    shifted = by_kind[("id_to_display_names", FRIENDLY_JUDGE)]
    assert shifted.severity == "FAIL"
    assert shifted.details["mapping"]["LLMJudge_2"] == ["Ambiguous mention"]
    assert "Ambiguous mention" not in shifted.details["mapping"]["LLMJudge"]

    mixed = by_kind[("display_name_to_ids", "LLMJudge")]
    assert mixed.details["mapping"][MAY_JUDGE] == ["Ambiguous mention"]

    isinstance_mix = by_kind[("display_name_to_ids", "IsInstance")]
    assert isinstance_mix.details["mapping"]["IsInstance('TimeRangeBuilderError')"] == ERROR_CASES
    assert len(by_kind) == 3


def test_time_range_coverage_flags_case_scoped_and_empty_dict_evaluators() -> None:
    coverage = run("time_range").by_check("evaluator-coverage")

    assert severities(coverage) == {
        "IsInstance('TimeRangeBuilderSuccess')": "FAIL",
        "IsInstance('TimeRangeBuilderError')": "FAIL",
        "ValidateTimeRange()[window_is_not_too_long]": "FAIL",
        "ValidateTimeRange()[window_is_not_in_the_future]": "FAIL",
        AGENT_CALLED_TOOL: "FAIL",
        MAY_JUDGE: "FAIL",
        FRIENDLY_JUDGE: "PASS",
        "UserMessageIsConcise()": "PASS",
    }
    # ValidateTimeRange returns {} for error outputs, so its assertions exist on 7 of 10.
    window = "ValidateTimeRange()[window_is_not_too_long]"
    (finding,) = [f for f in coverage if f.details["evaluator_id"] == window]
    assert finding.details["uncovered_case_runs"] == ERROR_CASES


def test_time_range_assertion_pass_rate_depends_on_the_estimator() -> None:
    result = run("time_range")
    group = estimator(result, "group", "assertions")

    assert group.severity == "WARN"
    assert group.details["values"] == 46
    assert group.details["pooled"] == pytest.approx(42 / 46)
    assert group.details["mean_of_cases"] == pytest.approx(0.923333, abs=1e-6)
    assert [f.severity for f in result.by_check("evaluator-errors")] == ["PASS"] * 8
    assert [f.severity for f in result.by_check("task-failures")] == ["PASS"]


def test_time_range_misses_the_stale_span_query() -> None:
    """AgentCalledTool returns a well-formed False, which no integrity check can flag."""
    result = run("time_range")
    assert estimator(result, "evaluator_id", AGENT_CALLED_TOOL).details["pooled"] == 0
    assert severities(result.by_check("evaluator-errors"))[AGENT_CALLED_TOOL] == "PASS"


@pytest.mark.parametrize(("name", "code"), [("title_case", 0), ("time_range", 1)])
def test_dogfood_cli_exit_codes(name: str, code: int, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["check", str(DOGFOOD / f"{name}.json")]) == code
    capsys.readouterr()
