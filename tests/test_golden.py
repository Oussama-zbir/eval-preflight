"""Golden scenarios from SPEC.md §9, run through the Python API.

A, B and D run twice: from the hand-written generic fixtures and from the
pydantic-evals fixtures generated by scripts/make_fixtures.py. C exists only as a
generated fixture (expectations as amended in SPEC §15); so does E, whose baseline is
D. A, C, D and E also run live through the in-memory path.
"""

from pathlib import Path

import pytest

from eval_preflight import CheckResult, Finding, check, check_pydantic_evals, load
from tests.scenarios import run_scenario

FIXTURES = Path(__file__).parent / "fixtures"
SOURCES = ["generic", "pydantic-evals"]

# Evaluator ids differ by source. pydantic-evals serializes Judge's single non-default
# argument (its first dataclass field) as ["strict"], without the field name, so the
# id renders it positionally (SPEC §7.2); the hand-written generic fixtures name it.
JUDGE_IDS = {
    "generic": ("Judge(rubric='strict')", "Judge(rubric='lenient')"),
    "pydantic-evals": ("Judge('strict')", "Judge('lenient')"),
}


def run_fixture(name: str, source: str = "generic") -> CheckResult:
    directory = FIXTURES / "pydantic_evals" if source == "pydantic-evals" else FIXTURES
    run = load(directory / name)
    assert run.source == source
    return check(run)


def by_evaluator(findings: list[Finding]) -> dict[str, Finding]:
    return {f.details["evaluator_id"]: f for f in findings}


@pytest.mark.parametrize("source", SOURCES)
def test_a_partial_coverage(source: str) -> None:
    result = run_fixture("partial_coverage.json", source)
    coverage = by_evaluator(result.by_check("evaluator-coverage"))
    errors = by_evaluator(result.by_check("evaluator-errors"))

    assert coverage["FlakyScore()"].severity == "FAIL"
    assert coverage["FlakyScore()"].message == "FlakyScore() scored 1/4 case-runs (25%)"
    assert errors["FlakyScore()"].severity == "FAIL"
    assert errors["FlakyScore()"].message == (
        "FlakyScore() errored on 3/4: RuntimeError: judge quota exhausted"
    )
    assert coverage["AlwaysScores()"].severity == "PASS"
    assert coverage["AlwaysScores()"].message == "AlwaysScores() scored 4/4 case-runs (100%)"
    assert errors["AlwaysScores()"].severity == "PASS"
    assert [f.severity for f in result.by_check("task-failures")] == ["PASS"]
    assert [f.severity for f in result.by_check("name-collision")] == ["PASS"]
    assert result.verdict == "FAIL"


@pytest.mark.parametrize("source", SOURCES)
def test_a_reported_aggregate_states_it_covers_one_case(source: str) -> None:
    # The JSON path has no reported aggregates; attach the number pydantic-evals reports.
    directory = FIXTURES / "pydantic_evals" if source == "pydantic-evals" else FIXTURES
    run = load(directory / "partial_coverage.json")
    run = run.model_copy(update={"reported_aggregates": {"FlakyScore": 1.0}})
    (finding,) = [
        f for f in check(run).by_check("aggregation-consistency") if "reported_key" in f.details
    ]
    assert finding.severity == "PASS"
    assert finding.message == 'reported "FlakyScore" = 1 reproduced from 1 of 4 cases'


@pytest.mark.parametrize("source", SOURCES)
def test_b_name_shift(source: str) -> None:
    result = run_fixture("name_shift.json", source)
    strict, lenient = JUDGE_IDS[source]
    collisions = {f.message: f for f in result.by_check("name-collision")}

    assert set(collisions) == {
        f'"Judge" → {strict} on c1; {lenient} on c2, c3, c4',
        f'{lenient} → "Judge_2" on c1; "Judge" on c2, c3, c4',
    }
    assert all(f.severity == "FAIL" for f in collisions.values())

    coverage = by_evaluator(result.by_check("evaluator-coverage"))
    assert coverage[strict].severity == "FAIL"
    assert coverage[strict].message == f"{strict} scored 1/4 case-runs (25%)"
    assert coverage[lenient].severity == "PASS"
    assert by_evaluator(result.by_check("evaluator-errors"))[strict].severity == "FAIL"
    assert result.verdict == "FAIL"


def test_c_repeat_divergence() -> None:
    result = run_fixture("repeat_divergence.json", "pydantic-evals")
    outputs = [f"CaseChecks()[{key}]" for key in ("a_check", "b_check_1", "b_check_2", "b_check_3")]

    (group,) = [f for f in result.by_check("aggregation-consistency") if f.details["group"]]
    assert group.severity == "WARN"
    assert group.message == "all assertions: pooled mean 0.25 vs mean of per-case means 0.5"

    # Each named output exists on one case only: 2 of 4 case-runs (SPEC §15, amendment 1).
    coverage = by_evaluator(result.by_check("evaluator-coverage"))
    assert list(coverage) == outputs
    assert all(f.severity == "FAIL" for f in coverage.values())
    assert {f.message.split(" scored ")[1] for f in coverage.values()} == {"2/4 case-runs (50%)"}

    assert [f.severity for f in result.by_check("name-collision")] == ["PASS"]
    assert [f.severity for f in result.by_check("task-failures")] == ["PASS"]
    assert {f.severity for f in result.by_check("evaluator-errors")} == {"PASS"}
    aggregation = result.by_check("aggregation-consistency")
    assert {f.severity for f in aggregation if f.details["evaluator_id"]} == {"PASS"}
    assert result.verdict == "FAIL"


@pytest.mark.parametrize("source", SOURCES)
def test_d_clean_run_has_no_false_positives(source: str) -> None:
    result = run_fixture("clean_run.json", source)
    assert len(result.by_check("aggregation-consistency")) == 3  # 2 evaluators + assertions
    assert {f.severity for f in result.findings} == {"PASS"}
    assert result.verdict == "PASS"
    result.raise_if_failed()


# In-memory path: the same scenarios run live, with the numbers pydantic-evals itself
# reports from report.averages() (SPEC §7.2).


def test_a_in_memory_reported_aggregate_states_it_covers_one_case() -> None:
    result = check_pydantic_evals(run_scenario("partial_coverage"))
    reported = {
        f.details["reported_key"]: f
        for f in result.by_check("aggregation-consistency")
        if "reported_key" in f.details
    }
    assert result.run.reported_aggregates == {"FlakyScore": 1.0, "AlwaysScores": 0.5}
    assert reported["FlakyScore"].severity == "PASS"
    assert (
        reported["FlakyScore"].message == 'reported "FlakyScore" = 1 reproduced from 1 of 4 cases'
    )
    assert result.verdict == "FAIL"


def test_c_in_memory_reported_pass_rate_is_the_mean_of_per_case_means() -> None:
    result = check_pydantic_evals(run_scenario("repeat_divergence"))
    assert result.run.reported_aggregates == {"assertions": 0.5}
    (reported,) = [
        f for f in result.by_check("aggregation-consistency") if "reported_key" in f.details
    ]
    assert reported.severity == "PASS"
    assert reported.message == (
        'reported "assertions" = 0.5 reproduced as the mean of per-case means '
        "from 2 of 2 cases (pooled mean: 0.25)"
    )
    assert reported.details["reproduced_by"] == "mean_of_cases"


def test_d_in_memory_clean_run_passes() -> None:
    result = check_pydantic_evals(run_scenario("clean_run"))
    assert {f.severity for f in result.findings} == {"PASS"}
    assert result.exit_code() == 0


def assert_scenario_e(result: CheckResult) -> None:
    comparability = result.by_check("baseline-comparability")
    assert [(f.severity, f.message) for f in comparability] == [
        ("WARN", "cases differ from the baseline: removed c4"),
        ("FAIL", "Relevance() coverage dropped from 4/4 (100%) in the baseline to 2/3 (66.6%)"),
    ]
    coverage = by_evaluator(result.by_check("evaluator-coverage"))
    errors = by_evaluator(result.by_check("evaluator-errors"))
    assert coverage["Relevance()"].severity == "FAIL"
    assert errors["Relevance()"].severity == "FAIL"
    assert errors["Relevance()"].message == (
        "Relevance() errored on 1/3: ValueError: cannot judge an empty answer"
    )
    assert result.verdict == "FAIL"


def test_e_baseline() -> None:
    directory = FIXTURES / "pydantic_evals"
    candidate, baseline = (
        load(directory / "baseline_candidate.json"),
        load(directory / "clean_run.json"),
    )
    assert_scenario_e(check(candidate, baseline=baseline))


def test_e_baseline_in_memory() -> None:
    result = check_pydantic_evals(
        run_scenario("baseline_candidate"), baseline=run_scenario("clean_run")
    )
    assert_scenario_e(result)
