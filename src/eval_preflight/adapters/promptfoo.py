"""promptfoo adapter (SPEC.md §7.3): the JSON written by `promptfoo eval -o results.json`.

Verified against exports generated by running promptfoo (scripts/make_promptfoo_fixtures.py):

- Each row of `results.results` is one case-run. The case id is the test's `description`,
  else its `vars` as sorted JSON; `repeatIndex` (absent without `--repeat`) is the run index.
- `failureReason` is a number: 0 none, 1 assertion failure, 2 error. Only 2 is a task error.
  The row's `error` field is not: promptfoo also sets it when an assertion or judge failed.
- Each `gradingResult.componentResults` entry with an `assertion` is one `assertion`
  measurement whose value is `pass`. The id is the assertion type and value; the display
  name is the assertion's `metric`, the name promptfoo aggregates it under, else the id.
  An `assert-set` adds a summary entry without `assertion` next to its flattened children;
  the summary is skipped so nothing counts twice.
- A judge that could not grade (`metadata.graderError`) is a measurement error, not a FAIL:
  promptfoo records it as `pass: false, score: 0` and counts it as a failed assertion.

An export with more than one prompt or provider is rejected: which of them a case id should
include decides what a baseline comparison compares, so it is left to the user.
"""

from __future__ import annotations

import json
from typing import Any

from pydantic import BaseModel, Field, ValidationError

from eval_preflight.adapters import LoadError, loads_json
from eval_preflight.model import CaseResult, EvalRun, EvaluatorRef, Measurement

SOURCE = "promptfoo"
RESULTS_VERSION = 3
TASK_ERROR = 2  # promptfoo's ResultFailureReason.ERROR


class _Assertion(BaseModel):
    type: str
    value: Any = None
    metric: str | None = None


class _Component(BaseModel):
    assertion: _Assertion | None = None
    passed: bool | None = Field(default=None, alias="pass")
    reason: str | None = None
    metadata: dict[str, Any] | None = None


class _Grading(BaseModel):
    component_results: list[_Component] | None = Field(default=None, alias="componentResults")


class _TestCase(BaseModel):
    description: str | None = None


class _Provider(BaseModel):
    id: str


class _Row(BaseModel):
    test_case: _TestCase = Field(default_factory=_TestCase, alias="testCase")
    vars: dict[str, Any] = {}
    provider: _Provider | None = None
    prompt_idx: int | None = Field(default=None, alias="promptIdx")
    repeat_index: int = Field(default=0, ge=0, alias="repeatIndex")
    failure_reason: int = Field(default=0, alias="failureReason")
    error: str | None = None
    grading_result: _Grading | None = Field(default=None, alias="gradingResult")


def looks_promptfoo(document: object) -> bool:
    """A JSON object with promptfoo's `evalId` or its nested `results.results` list."""
    if not isinstance(document, dict):
        return False
    results = document.get("results")
    return "evalId" in document or (
        isinstance(results, dict) and isinstance(results.get("results"), list)
    )


def evaluator_id(assertion: _Assertion) -> str:
    """`type(value)`: a string value as its repr, any other value as sorted JSON."""
    if assertion.value is None:
        return f"{assertion.type}()"
    if isinstance(assertion.value, str):
        return f"{assertion.type}({assertion.value!r})"
    return f"{assertion.type}({json.dumps(assertion.value, sort_keys=True)})"


def parse_promptfoo(text: str, *, default_name: str) -> EvalRun:
    try:
        document = loads_json(text)
    except json.JSONDecodeError as exc:
        raise LoadError(f"promptfoo export is not valid JSON ({exc.msg})") from exc
    if not isinstance(document, dict) or not isinstance(document.get("results"), dict):
        raise LoadError("promptfoo export has no `results` object")
    results = document["results"]
    version = results.get("version")
    if version != RESULTS_VERSION:
        raise LoadError(
            f"unsupported promptfoo results version {version!r}; expected {RESULTS_VERSION}"
        )
    rows = results.get("results")
    if not isinstance(rows, list) or not rows:
        raise LoadError("no case results in input")
    try:
        parsed = [_Row.model_validate(row) for row in rows]
    except ValidationError as exc:
        raise LoadError(f"invalid promptfoo result row: {exc}") from exc

    combinations = {(row.prompt_idx, row.provider.id if row.provider else None) for row in parsed}
    if len(combinations) > 1:
        raise LoadError(
            f"promptfoo export has {len(combinations)} prompt/provider combinations; "
            "eval-preflight checks one at a time (run promptfoo with --filter-providers "
            "and --filter-prompts to export each)"
        )

    config = document.get("config")
    description = config.get("description") if isinstance(config, dict) else None
    metadata = document.get("metadata")
    version_tag = metadata.get("promptfooVersion") if isinstance(metadata, dict) else None
    try:
        return EvalRun(
            name=description if isinstance(description, str) and description else default_name,
            source=SOURCE,
            source_version=version_tag if isinstance(version_tag, str) else None,
            cases=[_case(row) for row in parsed],
        )
    except ValidationError as exc:
        raise LoadError(str(exc)) from exc


def _case(row: _Row) -> CaseResult:
    case_id = row.test_case.description or json.dumps(row.vars, sort_keys=True)
    if row.failure_reason == TASK_ERROR:
        return CaseResult(
            case_id=case_id,
            run_index=row.repeat_index,
            task_error=(row.error or "task error").splitlines()[0],
        )
    components = row.grading_result.component_results if row.grading_result else None
    measurements = [
        _measurement(component, component.assertion)
        for component in components or []
        if component.assertion is not None  # skips an assert-set's summary entry
    ]
    return CaseResult(case_id=case_id, run_index=row.repeat_index, measurements=measurements)


def _measurement(component: _Component, assertion: _Assertion) -> Measurement:
    identity = evaluator_id(assertion)
    ref = EvaluatorRef(id=identity, display_name=assertion.metric or identity, kind="assertion")
    if (component.metadata or {}).get("graderError") is True:
        return Measurement(evaluator=ref, value=None, error=component.reason or "grader error")
    if component.passed is None:
        raise LoadError(f"assertion {identity} has no `pass` value")
    return Measurement(evaluator=ref, value=component.passed)
